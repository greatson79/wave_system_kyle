def body(text, indent=0, space_after=6):
    p = doc.add_paragraph(text)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.left_indent = Cm(indent)
    for run in p.runs:
        run.font.name = 'Malgun Gothic'
        run.font.size = Pt(10.5)
    return p

def bullet(text, bold_prefix=None, indent=0.5):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.left_indent = Cm(indent)
    p.paragraph_format.space_after = Pt(3)
    if bold_prefix:
        r = p.add_run(bold_prefix)
        r.bold = True
        r.font.size = Pt(10.5)
        r.font.name = 'Malgun Gothic'
    r2 = p.add_run(text)
    r2.font.size = Pt(10.5)
    r2.font.name = 'Malgun Gothic'

def table_2col(header, rows, col_widths=(4, 10)):
    t = doc.add_table(rows=1 + len(rows), cols=2)
    t.style = 'Light Shading Accent 1'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    hdr[0].text = header[0]
    hdr[1].text = header[1]
    for i, (a, b) in enumerate(rows):
        row = t.rows[i + 1].cells
        row[0].text = a
        row[1].text = b
    doc.add_paragraph()

def table_multi(headers, rows):
    cols = len(headers)
    t = doc.add_table(rows=1 + len(rows), cols=cols)
    t.style = 'Light Shading Accent 1'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        t.rows[0].cells[i].text = h
    for i, row_data in enumerate(rows):
        for j, val in enumerate(row_data):
            t.rows[i + 1].cells[j].text = val
    doc.add_paragraph()

def divider():
    p = doc.add_paragraph('─' * 60)
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(2)
    for run in p.runs:
        run.font.color.rgb = RGBColor(180, 180, 180)
        run.font.size = Pt(8)

def alert_box(text, color=(139, 0, 0)):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.5)
    p.paragraph_format.space_after = Pt(8)
    run = p.add_run('⚠ ' + text)
    run.bold = True
    run.font.size = Pt(10.5)
    run.font.color.rgb = RGBColor(*color)
    run.font.name = 'Malgun Gothic'

